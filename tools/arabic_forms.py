#!/usr/bin/env python3
"""Write src/arabic_forms.rs: the tables src/rtl.rs joins Arabic letters with, from the
Unicode Character Database. egui draws one glyph per character and knows no OpenType
shaping, so a joined letter is drawn as its presentation form (U+FB50-FDFF, U+FE70-FEFF).

Usage: tools/arabic_forms.py UnicodeData.txt ArabicShaping.txt src/arabic_forms.rs
(both from https://www.unicode.org/Public/UCD/latest/ucd/)
"""
import re
import sys

data_path, shaping_path, out_path = sys.argv[1:4]
FORMS = ("isolated", "final", "initial", "medial")
# The blocks whose letters and marks take part.
ARABIC = [(0x0600, 0x06FF), (0x0750, 0x077F), (0x0870, 0x08FF)]


def arabic(cp):
    return any(a <= cp <= b for a, b in ARABIC)


version = None
joining = {}
for line in open(shaping_path, encoding="utf-8"):
    m = re.match(r"# ArabicShaping-(\d+\.\d+\.\d+)\.txt", line)
    if m:
        version = m.group(1)
    line = line.split("#")[0].strip()
    if line:
        cp, _, jt, _ = [f.strip() for f in line.split(";")]
        joining[int(cp, 16)] = jt

forms = {}  # letter -> {form: presentation character}
lam_alef = {}  # alef -> {form: ligature}
transparent = set()
for line in open(data_path, encoding="utf-8"):
    f = line.split(";")
    cp, cat, decomp = int(f[0], 16), f[2], f[5]
    if arabic(cp) and cat in ("Mn", "Me", "Cf") and cp not in joining:
        transparent.add(cp)  # ArabicShaping.txt: unlisted Mn, Me and Cf are T
    m = re.fullmatch(r"<(isolated|final|initial|medial)> ([0-9A-F]+)( [0-9A-F]+)?", decomp)
    if not m or not (0xFB50 <= cp <= 0xFDFF or 0xFE70 <= cp <= 0xFEFF):
        continue
    form, a, b = m.group(1), int(m.group(2), 16), m.group(3)
    if b is not None:
        if a == 0x0644 and joining.get(int(b, 16)) == "R":
            lam_alef.setdefault(int(b, 16), {})[form] = cp
        continue
    have = forms.setdefault(a, {})
    # Forms-B (U+FE70-FEFF) is what fonts carry most; it wins over a Forms-A duplicate.
    if form not in have or cp >= 0xFE70 > have[form]:
        have[form] = cp
transparent |= {cp for cp, jt in joining.items() if jt == "T" and arabic(cp)}


def joins(letter, have):
    """D: joins on both sides; R: only to the letter before. One that Unicode gives no
    joined forms for is drawn alone, so it joins nothing (U)."""
    jt = joining.get(letter, "U")
    if jt == "D" and all(k in have for k in FORMS):
        return "D"
    if jt in ("D", "R") and "final" in have:
        return "R"
    return "U"


def ranges(cps):
    out = []
    for cp in sorted(cps):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def ch(cp):
    return "'\\u{%x}'" % cp if cp else "'\\0'"


rows = [(cp, joins(cp, have), have) for cp, have in sorted(forms.items())]
rows = [r for r in rows if r[1] != "U"]
causing = sorted(cp for cp, jt in joining.items() if jt == "C" and (arabic(cp) or cp == 0x200D))
with open(out_path, "w", encoding="utf-8") as out:
    out.write(f"// Generated by tools/arabic_forms.py from Unicode {version} (UnicodeData.txt and ArabicShaping.txt). Do not edit.\n\n")
    out.write("/// Letters that join, sorted: (letter, joins on both sides, its isolated, final, initial\n")
    out.write("/// and medial forms); '\\0' for a form a letter joined on one side has none of.\n")
    out.write("pub const FORMS: &[(char, bool, [char; 4])] = &[\n")
    for cp, jt, have in rows:
        cells = ", ".join(ch(have.get(k, 0) if jt == "D" or k in ("isolated", "final") else 0) for k in FORMS)
        out.write(f"    ({ch(cp)}, {'true' if jt == 'D' else 'false'}, [{cells}]),\n")
    out.write("];\n\n")
    out.write("/// Lam then one of these alefs is drawn as one ligature: (alef, isolated, final).\n")
    out.write("pub const LAM_ALEF: &[(char, char, char)] = &[\n")
    for alef, have in sorted(lam_alef.items()):
        out.write(f"    ({ch(alef)}, {ch(have['isolated'])}, {ch(have['final'])}),\n")
    out.write("];\n\n")
    out.write("/// Join to the letters on both sides without changing shape (tatweel, ZWJ).\n")
    out.write("pub const JOIN_CAUSING: &[char] = &[" + ", ".join(ch(c) for c in causing) + "];\n\n")
    out.write("/// Marks that joining looks through to the letter beyond, as inclusive ranges.\n")
    out.write("pub const TRANSPARENT: &[(char, char)] = &[\n")
    for a, b in ranges(transparent):
        out.write(f"    ({ch(a)}, {ch(b)}),\n")
    out.write("];\n")
